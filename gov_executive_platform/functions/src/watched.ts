/**
 * قائمةُ المراقَبين — تنقيحُها وحدُّها.
 *
 * ــــ لماذا حدٌّ أصلاً ــــ
 *
 * القائمةُ تُحمل في **بطاقة الدخول** (`w`)، لأن قواعدَ Firestore تحتكم إلى
 * البطاقة وحدها: قاعدةٌ تقرأ مستنداً آخر تكلّف قراءةً في كل تقييم. وللبطاقة
 * حدٌّ صارم عند **ألف بايت**، تجاوزُه يُسقط الختمَ كلَّه — فلا يبقى دورٌ ولا
 * إدارةٌ ولا صلاحية، لا قائمةُ المراقَبة وحدها.
 *
 * والحجمُ مقيسٌ لا مظنون: بطاقةُ مراقبٍ بصلاحياته الأربع تبلغ ١٨٣ بايت
 * فارغةً، و٤٩٩ بعشرة أسماء، و**٨٠٩ بعشرين**، و٩٦٤ بخمسةٍ وعشرين — على
 * الحافّة — و١١١٩ بثلاثين فتسقط. فالعشرون مسافةٌ كافيةٌ لمفتاحٍ يُضاف بعدُ.
 *
 * وهو حدُّ `MAX_HEADED_SECTIONS` نفسُه ولسببه.
 *
 * ــــ ولماذا وحدةٌ خالصة ــــ
 *
 * `index.ts` لا يعمل إلا بـFirebase حيّ، أي خارج مدى أي اختبار. وهو النمطُ
 * القائم في هذا المجلّد (`status_scope.ts` و`user_scope.ts` و`sla.ts`).
 */

/** أقصى عددٍ يُراقَب — راجع قياسَ الحجم أعلاه. */
export const MAX_WATCHED = 20;

/** ما تردّه [sanitizeWatched]: القائمةُ النظيفة، وما أُسقط منها ولماذا. */
export type WatchedResult = {
  /** القائمةُ بعد التنقيح — بلا تكرارٍ ولا فراغٍ ولا صاحبِها. */
  uids: string[];
  /** هل تُجووز الحدُّ؟ وعندها لا تُقتطع بصمت بل يُردّ الطلب. */
  overLimit: boolean;
  /** هل كان صاحبُ القائمة فيها؟ — يُسقط بلا رفضِ الطلب. */
  droppedSelf: boolean;
};

/**
 * يُنقّي قائمةَ المراقَبين الواردةَ من العميل.
 *
 * والتنقيحُ ثلاثةٌ كلٌّ منها قرار:
 *
 * **(١) المكرَّرُ يُطرح** — لا لأنه يضرّ، بل لأنه يأكل من الحدّ: من أرسل
 * اسماً عشرين مرّةً يُقال له «بلغتَ العشرين» وهو لم يراقب أحداً.
 *
 * **(٢) والفارغُ يُطرح** — معرّفٌ فارغٌ في القائمة يجعل `uid in w` صادقاً
 * لكلّ مستندٍ بلا حقل `uid`، فيفتح ما لم يُفتح. وهو بعينه الشرطُ الذي
 * نوقش في `isSectionHeadOf`.
 *
 * **(٣) وصاحبُها يُطرح بلا رفض** — المرءُ يرى نفسَه بقواعدَ أخرى قائمة،
 * فوجودُه في قائمته لغوٌ يأكل من الحدّ. ورفضُ الطلب لأجله تشديدٌ بلا فائدة.
 *
 * **والحدُّ لا يُقتطع**: قائمةٌ من إحدى وعشرين تُردّ برسالةٍ تسمّي السبب.
 * فالاقتطاعُ الصامت يترك مسؤولَ النظام يظنّ أنه سمّى واحداً وعشرين، ويظنّ
 * المراقبُ أنه يرى الكلّ — ولا يُكتشف إلا حين يُسأل عمّا لم يره.
 *
 * @param {unknown} raw ما ورد من العميل — قد لا يكون قائمةً أصلاً.
 * @param {string} ownerUid صاحبُ القائمة، يُطرح منها.
 * @return {WatchedResult} القائمةُ النظيفة وخبرُ ما وقع.
 */
export function sanitizeWatched(raw: unknown, ownerUid: string): WatchedResult {
  const list = Array.isArray(raw) ? raw : [];
  const seen = new Set<string>();
  let droppedSelf = false;
  for (const item of list) {
    if (typeof item !== "string") continue;
    const uid = item.trim();
    if (uid === "") continue;
    if (uid === ownerUid) {
      droppedSelf = true;
      continue;
    }
    seen.add(uid);
  }
  const uids = [...seen];
  return {uids, overLimit: uids.length > MAX_WATCHED, droppedSelf};
}

/**
 * رسالةُ تجاوزِ الحدّ — تسمّي العدد والحدّ معاً.
 *
 * و«تجاوزتَ الحدّ» وحدَها تترك من اختار ثلاثين يحذف واحداً واحداً حتى يمرّ.
 *
 * @param {number} count العددُ المُرسَل بعد التنقيح.
 * @return {string} الرسالةُ كما تُعرض.
 */
export function overLimitMessage(count: number): string {
  return `لا يمكن أن يراقب المستخدمُ أكثر من ${MAX_WATCHED} شخصاً، ` +
    `وقد اختِير ${count}. والحدُّ ليس اختياراً: قائمةُ المراقَبة تُحمل في ` +
    "بطاقة الدخول ولها حدُّ حجمٍ صارم، وتجاوزُه يُسقط صلاحياتِ المستخدم كلَّها. " +
    `فيُرفع من القائمة ${count - MAX_WATCHED} على الأقل.`;
}
