  /// يجمع خانات الملف في وصف واحد مقروء، مع تسمية كل خانة حتى يعرف القارئ
  /// من أين جاءت المعلومة.
  static String _describe({
    required String desc,
    String beneficiary = '',
    String plan = '',
    String notes = '',
    String similarTo = '',
  }) {
    final parts = <String>[];
    if (desc.isNotEmpty) parts.add(desc);
    if (beneficiary.isNotEmpty) parts.add('الجهة المستفيدة: $beneficiary');
    if (plan.isNotEmpty) parts.add('الخطة الزمنية بالملف: $plan');
    if (notes.isNotEmpty) parts.add('ملاحظات: $notes');
    if (similarTo.isNotEmpty) parts.add('يشبه موضوعاً: $similarTo — راجعهما قبل الدمج.');
    return parts.join('\n');
  }

  static Project _p({
    required String id,
    required String dept,
    required String name,
    required String desc,
    String beneficiary = '',
    String plan = '',
    String notes = '',
    String similarTo = '',
    DateTime? start,
    DateTime? due,
    required ProjectStatus status,
    required double progress,
    PriorityLevel priority = PriorityLevel.medium,
    List<String> team = const [],
  }) =>
      Project(
        id: id,
        departmentId: dept,
        name: name,
        description: _describe(
          desc: desc,
          beneficiary: beneficiary,
          plan: plan,
          notes: notes,
          similarTo: similarTo,
        ),
        startDate: start ?? _yearStart,
        dueDate: due ?? _yearEnd,
        status: status,
        priority: priority,
        progressPercent: progress,
        executorNames: team,
      );

