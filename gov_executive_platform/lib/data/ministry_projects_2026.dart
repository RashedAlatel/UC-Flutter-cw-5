/// بيانات ملفَّي متابعة المشروعات ٢٠٢٦ اللذين زوّدنا بهما مسؤول النظام:
/// **١٠٨ مشاريع موزّعة على ستة أقسام**.
///
/// الملف الثاني (٢٨ صفحة) يحتوي الأول (١٨ صفحة) **كاملاً بلا تغيير** — قورنت
/// صفحاته ١١–٢٨ بصفحات الأول ١–١٨ فجاءت متطابقة. فالجديد فيه قسم واحد فقط هو
/// «قسم تخطيط المشروعات» (٣٧ مشروعاً). لذلك بقيت معرّفات المشاريع الـ٧١
/// السابقة كما هي حرفياً، وأُضيف القسم الجديد بمعرّفات مستقلة — فإعادة
/// الاستيراد **تدمج ولا تُكرّر**، وهو ما يمنع ازدواج البيانات القديمة.
///
/// كيف قُرئ الملف:
/// * كل قسم في الملف أصبح **إدارة** في المنصة، ورئيس القسم المذكور في ترويسة
///   الصفحة أصبح `headName` لها. أقسام «مراقبة متابعة المشروعات» رئيسها
///   شيماء العلي، وقسم النظم الآلية رئيسه آلاء الضفيري (تكليف)، وقسم صيانة
///   النظم رئيسه أشواق الخباز (تكليف)، وقسم حفظ الوثائق شاغر.
/// * كل صف أصبح **مشروعاً** باسمه ووصفه وجهته المستفيدة وفريق عمله وملاحظاته
///   كما وردت حرفياً في الملف. حين تكرّر اسم المشروع داخل القسم نفسه (مثل
///   «إدارة الرسوم القضائية» و«نظام التنفيذ») أُضيفت لاحقة مميّزة من الوصف
///   حتى لا تلتبس المشاريع على المستخدم، مع بقاء النص الأصلي في الوصف.
/// * **الحالة ونسبة الإنجاز مستنتجتان** من نص خانتي «تاريخ البدء - تاريخ
///   الانتهاء» و«ملاحظات»: «تم/انتهى/تم التدشين» ← مكتمل، و«جاري العمل/مستمر/
///   قائم/تحت الاختبار/المرحلة التجريبية» ← على المسار، و«لم يبدأ/قيد الدراسة/
///   مخطط» ← مهدّد بالخطر (وهي الحالة الوحيدة التي تُظهر البند في تنبيهات
///   المتابعة، وهذا مقصود لأن هذه البنود تحتاج قراراً). تحتاج مراجعة يدوية
///   لبعض البنود.
/// * **التواريخ**: البنود التي لم يذكر الملف لها تاريخاً أُعطيت مدى السنة
///   المالية للملف (١ يناير ← ٣١ ديسمبر ٢٠٢٦)، ونص الخانة الأصلي محفوظ في
///   الوصف تحت «الخطة الزمنية بالملف» حتى لا تضيع المعلومة.
///
/// * **بنود يشبه بعضها بعضاً**: أربعة مشاريع في قسم التخطيط تتناول مواضيع
///   تتناولها مشاريع في أقسام أخرى، لكنها سطور رسمية مستقلة بمسؤولين
///   مختلفين. أُبقيت كما وردت، وأُضيف لوصف كلٍّ منها ونظيره سطر «يشبه
///   موضوعاً» يشير للآخر، فيراهما مسؤول النظام مترابطين ويدمج ما يشاء يدوياً
///   بدل أن نحذف عنه معلومة لا نملك قرار حذفها.
///
/// المعرّفات ثابتة، فتكرار الاستيراد آمن (merge) ولا يُنشئ سجلات مكرّرة.
/// لا يمسّ هذا الملف بأي شكل بوابات الاعتماد الثلاث (تسجيل الأعضاء، إضافة
