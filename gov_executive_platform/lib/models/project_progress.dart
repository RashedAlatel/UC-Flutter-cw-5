// حالةُ المشروع من نسبة إنجازه — **القاعدةُ الواحدة**.
//
// ــــ لماذا وحدةٌ نقيّة ــــ
//
// القاعدةُ كانت مكتوبةً داخل `addDailyUpdate` وحدها في `app_store.dart`،
// وهي دالّةٌ طويلة تكتب في ست مجموعات. ثم صار للنسبة بابٌ ثانٍ — تصحيحُها
// على مشروعٍ اكتمل — فلو نُسخت القاعدةُ إليه لَافترقتا بأوّل تعديل: تحديثٌ
// يوميّ يُخرج من الاكتمال وتصحيحٌ لا يُخرج، أو العكس.
//
// فهي هنا بلا Firestore ولا `BuildContext`، يُقاس كلُّ انتقالٍ فيها وحده
// وتُقلب كلُّ قاعدةٍ بطفرة. وهو نمطٌ قائم في المنصة: `splitDeleted`
// و`diffMaps` و`workUpdateOutcome` و`periodic_report.dart`.
//
// ــــ والعطلُ الذي أوجب إخراجها ــــ
//
// «المكتملُ يبقى مكتملاً» كان حكماً بلا استثناء: من أدخل ١٠٠٪ سهواً بقي
// مشروعُه «مكتملاً» وإن صحّح الرقمَ إلى ٨٠٪ — شارةٌ تقول شيئاً ورقمٌ يقول
// غيرَه. فصار النزولُ عن المئة يُخرج من الاكتمال.
library;

import 'enums.dart';

/// الحدُّ الذي يُعدّ بعده المشروعُ متأخّراً في هذا الحساب.
///
/// خمسةٌ لا صفر: يومٌ أو يومان بعد الموعد أمرٌ يقع في العمل ويُدرَك، ووسمُ
/// المشروع «متأخّراً» عندهما يُفقد الوسمَ معناه. وهو حدٌّ قائمٌ من قبل،
/// يُنقل كما هو ولا يُبدَّل هنا.
const int kDelayedAfterDays = 5;

/// الحالةُ التي يصير إليها المشروع بعد كتابة [progress].
///
/// ــ الترتيبُ مقصود، والأشدُّ يُقدَّم ــ
///
/// ١. **المئةُ تُكمل** — ولو كان متأخّراً: الإنجازُ وقع، والتأخيرُ وصفُ ما
///    مضى لا حالُ اليوم.
/// ٢. **وما دونها ليس مكتملاً** — وهذا هو ما كان ناقصاً. فالمكتملُ الذي
///    نزلت نسبتُه يعود إلى ما يقوله موعدُه، ولا يبقى مكتملاً برقمٍ يناقضه.
/// ٣. ثم التأخيرُ، ثم العائق، ثم التقدّم — أشدُّها أولاً، فالشارةُ تقول
///    أسوأَ ما في المشروع لا آخرَ ما وقع فيه.
///
/// [previousProgress] تُستعمل في شرطٍ واحد: «تقدّمٌ يُعيد المشروع إلى
/// المسار». وتُترك `null` حين لا يكون هناك ما يُقارَن به — وحينها لا يُدّعى
/// تقدّمٌ ولا تُختلق حركة، فتبقى الحالُ كما هي.
ProjectStatus statusForProgress({
  required double progress,
  required ProjectStatus current,
  required int delayDays,
  required bool hasNewRisk,
  double? previousProgress,
}) {
  if (progress >= 100) return ProjectStatus.completed;

  // ــ النزولُ عن المئة يُخرج من الاكتمال ــ
  //
  // ولا يكفي أن تسقط الحالةُ إلى `current`: تلك `completed` نفسُها، فيعود
  // المشروع إليها من حيث خرج. فتُحسب حالُه من جديد كأنه لم يكن مكتملاً.
  final wasCompleted = current == ProjectStatus.completed;

  if (delayDays > kDelayedAfterDays) return ProjectStatus.delayed;
  if (hasNewRisk) return ProjectStatus.atRisk;
  if (previousProgress != null && progress > previousProgress) {
    return ProjectStatus.onTrack;
  }
  // خرج من الاكتمال ولا تأخيرَ ولا عائق: «على المسار» — ولا يُترك على
  // `completed` وقد نزل رقمُه.
  return wasCompleted ? ProjectStatus.onTrack : current;
}
