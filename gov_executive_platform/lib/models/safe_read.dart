/// قراءةُ تاريخٍ ورقمٍ من قاعدةِ بياناتٍ **بلا مخطَّطٍ مُلزِم**.
///
/// ــــ الحادثةُ التي أوجبت هذين القارئين ــــ
///
/// اختفت مشاريعُ وزارة العدل كلُّها — مئةٌ وأربعةٌ وثمانون — يوماً كاملاً،
/// والسببُ مستندٌ واحد حمل `contractEndDate` نصّاً:
/// `'2026-05-17T00:00:00.000'`. كتبَه مسارُ اعتماد تعديل المشروع، وقرأه
/// النموذجُ `as Timestamp?` فرمى — والقراءةُ يومَها ذرّية، فأسقط المستندُ
/// الواحدُ الباقين معه. ولم يظهر على الشاشة حرفٌ يقول لماذا.
///
/// ــــ ولماذا وحدةٌ مشتركة ــــ
///
/// وُلد القارئان خاصَّين في `project.dart`. ثم جاء نموذجٌ ثانٍ يقرأ تواريخَ
/// وأرقاماً، فإمّا أن يُنسخا — فينحرف أحدُهما يوماً عن الآخر ويعود العطلُ
/// من الباب الذي لم يُصلَح — وإمّا أن يُخرَجا موضعاً واحداً يقرّر. وهذا هو.
///
/// و`project.dart` يبقى فيه `_date` و`_num` اسمَين يُحيلان إلى هنا: لا
/// نسختين، وحارسُ `model_cast_test.sh` يبقى يقرأ ما يعرف.
library;

import 'package:cloud_firestore/cloud_firestore.dart';

/// يقرأ تاريخاً من قيمةٍ **مهما كان نوعُها** — أو `null`.
///
/// ولا يُختلق تاريخ: ما لا يُقرأ يُقرأ **«غير مسجّل»** لا تاريخَ اليوم.
/// فعقدٌ ينتهي اليوم رقمٌ يُتّخذ عليه قرار، وهو أسوأ من فراغٍ صريح.
DateTime? readDate(Object? raw) {
  if (raw is Timestamp) return raw.toDate();
  if (raw is DateTime) return raw;
  if (raw is String) return DateTime.tryParse(raw.trim());
  return null;
}

/// يقرأ رقماً من قيمةٍ مهما كان نوعُها — أو `null`. نظيرُ [readDate].
///
/// وصفرٌ يُختلق أسوأ من فراغ: مدّةُ خطوةٍ صفراً تُقرأ «تقع في يومها»، وهي
/// دعوى لم يقلها أحد.
num? readNum(Object? raw) {
  if (raw is num) return raw;
  if (raw is String) return num.tryParse(raw.trim());
  return null;
}

/// يقرأ نصّاً مشذَّباً — والغائبُ والفارغُ سواء.
String readText(Object? raw) => raw is String ? raw.trim() : '';
