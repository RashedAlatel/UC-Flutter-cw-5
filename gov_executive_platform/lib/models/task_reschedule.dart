// إعادةُ جدولة مهمة — **القاعدةُ الواحدة** لموعدها الجديد.
//
// ــــ لماذا وحدةٌ نقيّة ــــ
//
// الحدُّ الذي طلبتَه — «بحيث لا يتجاوز مدة نهاية المشروع» — يجب أن يُقال في
// ثلاثة مواضع: الشاشةُ تمنع قبل الضغط، والمتجرُ يمنع قبل الكتابة، وقاعدةُ
// الخادم تردّ من التفّ عليهما. ولو كُتب في كلٍّ نسخةٌ لَافترقت بأول تعديل.
//
// فهي هنا بلا Firestore ولا `BuildContext`، تُقاس وحدها وتُقلب بطفرة — كنمط
// `statusForProgress` و`workUpdateOutcome` و`judgeChanges`.
//
// ــــ ولماذا الحدُّ أصلاً ــــ
//
// مهمةٌ موعدُها بعد نهاية مشروعها تعني مشروعاً «مكتملاً» وفيه عملٌ لم يبدأ
// موعدُه — فتتناقض شارةُ المشروع مع مهامّه، ويُقرأ التأخيرُ خطأً في كل
// تقرير. وهو الحدُّ نفسُه المطبَّق عند **إنشاء** المهمة منذ البداية، ولم
// يكن مطبَّقاً عند تعديلها لأن التعديل لم يكن موجوداً.
library;

import '../utils/formatters.dart';

/// سببُ ردّ الموعد الجديد — أو `null` إن كان مقبولاً.
///
/// ويُعاد نصّاً لا علَماً: هذا النصُّ نفسُه يُعرض في النافذة ويُعاد من
/// المتجر، فلا تُترجَم علامةٌ إلى عبارتين مختلفتين في موضعين.
String? taskDueDateRejection({
  required DateTime newDue,
  required DateTime projectDue,
}) {
  // المقارنةُ باليوم لا باللحظة: موعدٌ في اليوم نفسِه مقبولٌ مهما كانت
  // ساعتُه، ولولا ذلك لَرُدّ موعدٌ يوافق نهاية المشروع لفارق ساعات.
  final due = DateTime(newDue.year, newDue.month, newDue.day);
  final limit = DateTime(projectDue.year, projectDue.month, projectDue.day);
  if (due.isAfter(limit)) {
    return 'موعد المهمة لا يتجاوز موعد استحقاق المشروع '
        '(${Formatters.date(projectDue)}). '
        'ولتمديدها بعده يُعدَّل موعد المشروع أولاً — وله مسار اعتماد خاص به.';
  }
  return null;
}
