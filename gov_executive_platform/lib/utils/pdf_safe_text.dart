/// نصٌّ يمرّ في مولّد PDF بلا انهيار.
///
/// ــــ العطل الذي قيس، لا الذي خُمّن ــــ
///
/// مكتبةُ `pdf` تُرتّب العربية عبر حزمة `bidi`. وفي `Normalization._compose`
/// خللٌ يرمي `RangeError` حين يبدأ النصُّ بحرفٍ **قابلٍ للتفكيك** (أ إ آ ؤ ئ
/// — كلُّها همزةٌ فوق حرفٍ أو تحته) وتليه **حركةٌ** مباشرةً. فالمُفكِّك يخرج
/// علامتين متجاورتين في أوّل السلسلة، ويقرأ المؤلِّف ما قبلهما فيتجاوز الحدّ.
///
/// وقيس ذلك: «أُنجزت» و«أَنجزت» و«أّنجزت» و«أُ» تسقط كلُّها، بينما «مُشروع»
/// و«اُ» و«مهام أُنجزت» و«اأُنجزت» تمرّ — فالموضع أوّلُ السلسلة وحده،
/// والحرفُ قابلُ التفكيك وحده. راجع `test/pdf_safe_text_test.dart`.
///
/// ــــ ولماذا يلزم لا يُتجنَّب ــــ
///
/// لأن النصّ الداخل في التقرير ليس كلَّه من كتابتنا: أسماءُ المشاريع
/// والإدارات والإنجازات يكتبها المستخدم. ومشروعٌ اسمه «أُفق العدالة» كان
/// **يُسقط تصدير التقرير كلَّه** — بلا ملفٍّ ولا سببٍ مفهوم. وهو عطلٌ قائمٌ
/// في التقرير التنفيذي منذ أن وُجد، لا عطلٌ استحدثه التقرير الدوري.
///
/// وما يُفقد: حركةٌ واحدة على أوّل حرف. وما يُنقذ: الملفُّ كلُّه.
library;

/// علاماتُ التشكيل العربية: الفتحة والضمة والكسرة والشدّة والسكون والتنوين،
/// والألف الخنجرية، والهمزات العلوية والسفلية المفردة.
bool _isArabicMark(int c) =>
    (c >= 0x064B && c <= 0x0655) || c == 0x0670 || (c >= 0x06D6 && c <= 0x06ED);

/// يُسقط حركاتِ **الحرف الأول وحده** حين يكون قابلاً للتفكيك.
///
/// ولا يمسّ ما بعده: الشدّةُ في «مسجَّل» تبقى، والضمّةُ في «إنجازُ» تبقى —
/// فالنصُّ يُقرأ كما كُتب إلا في الموضع الذي يكسر المولّد.
String pdfSafeText(String text) {
  if (text.length < 2) return text;
  final first = text.codeUnitAt(0);
  // الحروف القابلة للتفكيك: أ إ آ ؤ ئ — وهي وحدها ما قيس أنه يكسر.
  const decomposable = {0x0622, 0x0623, 0x0625, 0x0624, 0x0626};
  if (!decomposable.contains(first)) return text;

  var i = 1;
  while (i < text.length && _isArabicMark(text.codeUnitAt(i))) {
    i++;
  }
  if (i == 1) return text;
  return text[0] + text.substring(i);
}
