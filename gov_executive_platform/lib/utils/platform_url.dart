/// عنوان المنصة كما يراه المتصفح — أساسُ الروابط المباشرة في البريد.
///
/// ــــ لماذا دالّة على [Uri] لا قراءةٌ مباشرة من `Uri.base`؟ ــــ
///
/// لأن `Uri.base` على جهاز Dart (الاختبارات، وأي تشغيل خارج المتصفح) هو
/// **مجلّد العمل** لا عنوان موقع: `file:///home/…`. ورابطٌ كهذا في بريدٍ
/// يصل موظفاً في الوزارة لا يفتح شيئاً، ولا شيء يقول له لماذا.
///
/// فالمنطق هنا يُختبر بعنوانٍ يُمرَّر، والقراءة الحقيقية في [platformBaseUrl].
String baseUrlOf(Uri uri) {
  // ما ليس http(s) ليس عنوان منصة — والفراغ يعني «لا رابط»، وهو ما تفهمه
  // `projectLink` فتُسقط سطر الرابط كلّه بدل أن تكتب رابطاً كاذباً.
  if (uri.scheme != 'http' && uri.scheme != 'https') return '';
  if (uri.host.isEmpty) return '';
  final port = uri.hasPort ? ':${uri.port}' : '';
  // المسار يبقى: المنصة قد تُستضاف تحت مجلّد، وحذفُه يكسر الرابط. والاستعلام
  // والوسم يسقطان — نضيف `project=` بأنفسنا، ولا معنى لحمل استعلام الجلسة.
  final path = uri.path == '/' ? '/' : uri.path;
  return '${uri.scheme}://${uri.host}$port$path';
}

/// عنوان المنصة الحالي، أو فراغٌ خارج المتصفح.
String platformBaseUrl() => baseUrlOf(Uri.base);
