// استعادة كلمة المرور — ما يُقال ولمن.
//
// ــــ ما الذي يُختبر هنا فعلاً؟ ــــ
//
// الإرسال نفسه يقوم به Firebase ولا يُختبر بلا شبكة. والذي **يمكن أن ينكسر
// بصمت** شيئان، وكلاهما قرارٌ أمني لا تفصيلُ واجهة:
//
// ١) **الإخفاء**: بريدٌ غير مسجَّل يجب أن يُقرأ **نجاحاً** لا خطأً. ولو
//    أُرجع خطؤه لَكشفت شاشةُ الدخول من هو مسجَّل في المنصة لأي أحدٍ يجرّب
//    البُرد الوزارية — بلا حساب ولا دخول. والنافذة تعرض النصّ الواحد على
//    شرط `error == null`، فالإخفاء يجب أن يكون **في الدالّة** لا في نصّها.
//
// ٢) **ترجمة الأخطاء**: الحساب الموقوف صار واقعاً منذ أن صار الإيقاف يعطّل
//    حساب المصادقة. وبلا ترجمةٍ له تظهر رسالة Firebase الإنجليزية الخام في
//    منصةٍ عربية، فلا يعرف صاحبه أن حسابه أُوقف أصلاً.
//
// والدالّتان تناديان `FirebaseAuth.instance` مباشرةً فلا تُستدعيان هنا.
// فالمُختبَر هو **قرار التصنيف** المشترك بينهما، مستخرَجاً كما هو مكتوب.
import 'dart:io';

import 'package:flutter_test/flutter_test.dart';

import 'package:gov_exec_platform/data/app_store.dart';

/// نصّ `sendPasswordReset` و`_mapAuthError` كما هما في الشيفرة.
///
/// فحصٌ نصّي، وهو أضعف من اختبارٍ حقيقي ويُقال ذلك صراحةً: لا يثبت أن
/// الدالّة **تعمل**، بل يمنع أن يسقط قرارُ الإخفاء بصمت في تعديل لاحق —
/// وهو قرارٌ سطرٌ واحدٌ يمحوه ولا يصيح تحليلٌ ولا اختبار واجهة.
String storeSource() => File('lib/data/app_store.dart').readAsStringSync();

void main() {
  group('النصّ الواحد للحالتين', () {
    test('لا يذكر أن الحساب موجود أو غير موجود', () {
      final notice = AppStore.passwordResetNotice;
      expect(notice, contains('إن كان هذا البريد مسجَّلاً'));
      expect(notice, isNot(contains('غير مسجَّل')));
      expect(notice, isNot(contains('لا يوجد حساب')));
    });

    // ولولا ذكرُ المدّة وصندوق المهمل لَبقي من أخطأ في كتابة بريده ينتظر
    // رسالةً لن تأتي بلا أن يعرف ماذا يفعل — وهو ثمن الإخفاء الوحيد.
    test('ويقول متى تصل وأين تُبحث', () {
      expect(AppStore.passwordResetNotice, contains('دقائق'));
      expect(AppStore.passwordResetNotice, contains('Spam'));
    });
  });

  group('الإخفاء مفروضٌ في الدالّة لا في نصّ الشاشة', () {
    test('البريد غير المسجَّل يُقرأ نجاحاً', () {
      expect(
        storeSource(),
        contains("if (e.code == 'user-not-found' || e.code == 'invalid-email') return null;"),
        reason: 'لولا هذا السطر لَعادت الشاشةُ تكشف من هو مسجَّل في المنصة',
      );
    });

    test('وكثرةُ الطلب تُقال — هي فشلٌ حقيقي لا إخفاء', () {
      expect(storeSource(), contains('أُرسلت رسائل كثيرة خلال وقت قصير'));
    });
  });

  group('ترجمة أخطاء الدخول', () {
    test('الحساب الموقوف يُقال له إنه موقوف', () {
      expect(storeSource(), contains("case 'user-disabled':"));
      expect(storeSource(), contains('هذا الحساب موقوف ولا يمكنه الدخول'));
    });

    // ومجموعةٌ واحدة عمداً مع «كلمة المرور غير صحيحة»: لو أُفرد «لا حساب بهذا
    // البريد» لَصارت شاشة الدخول هي الأخرى تكشف من هو مسجَّل.
    test('و«لا حساب بهذا البريد» يبقى مدموجاً فلا يكشف شيئاً', () {
      final src = storeSource();
      final i = src.indexOf("case 'user-not-found':");
      expect(i, greaterThan(0));
      final after = src.substring(i, i + 200);
      expect(after, contains('البريد الإلكتروني أو كلمة المرور غير صحيحة'));
    });
  });

  // حدود بوابة البريد: كل بريدٍ يكتبه إنسان يبقى باعتماد مسؤول النظام، وهذه
  // الرسالة ليست منه — يولّدها Firebase ويرسلها بنفسه. فلو بُنيت دالّةً
  // خلفية لَصار في المنصة مُرسِلُ بريدٍ ثانٍ **يقبل عنواناً من الطلب**.
  group('ولا تمرّ بأي مُرسِلٍ في الخادم', () {
    test('لا أثر لإعادة التعيين في functions/', () {
      final dir = Directory('functions/src');
      for (final f in dir.listSync().whereType<File>()) {
        expect(f.readAsStringSync(), isNot(contains('PasswordReset')),
            reason: 'إعادة التعيين تخرج من Firebase مباشرةً — راجع ${f.path}');
      }
    });
  });
}
