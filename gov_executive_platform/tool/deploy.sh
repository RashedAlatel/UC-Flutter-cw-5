#!/usr/bin/env bash
#
# نشر المنصة كاملةً بأمر واحد:  ./tool/deploy.sh
#
# لماذا سكربت بدل أربعة أوامر؟
#
# لأن النشر أجزاء منفصلة على Firebase، ونسيان أيٍّ منها لا يُنتج رسالة خطأ —
# بل منصةً تبدو سليمة وتتصرّف تصرّفاً قديماً:
#
#   • قواعد قاعدة البيانات (firestore.rules) — هي التي تقرّر من يقرأ ماذا.
#     نسيانها يعني شاشات فارغة ولافتة حمراء، مهما كانت شيفرة الموقع جديدة.
#   • قواعد التخزين (storage.rules) — مرفقات التحديثات اليومية.
#   • الدوال (functions) — الاعتماد وختم الصلاحيات على بطاقات الدخول.
#   • الموقع (hosting) — الواجهة التي يراها المستخدم.
#
# وقد ضاعت ثلاث جولات تشخيص على هذا بالضبط: شيفرة مبنيّة ومرفوعة، وموقع
# منشور بنصفها، وقواعد لم تُنشر إطلاقاً.
#
# والحارس في الخطوة الأولى ليس تزيّداً: `build_web.sh` كان **يحذّر** من الفرع
# المتأخّر، والتحذير يمرّ في سيل مخرجات البناء فلا يُقرأ. هنا **يتوقّف**.
#
# للتجاوز عمداً (نشر شيفرة محلية لم تُرفع بعد):  ./tool/deploy.sh --force
set -euo pipefail

cd "$(dirname "$0")/.."

FORCE=""
[ "${1:-}" = "--force" ] && FORCE="yes"

# shellcheck source=tool/worktree.sh
. ./tool/worktree.sh
# shellcheck source=tool/live_check.sh
. ./tool/live_check.sh

BRANCH="$(git rev-parse --abbrev-ref HEAD 2>/dev/null || echo '?')"

# ــــ معرّف المشروع يُقرأ من الملف ويُمرَّر صراحةً في كل أمر ــــ
#
# ولا يُترك لحالة `firebase use` المحفوظة خارج المستودع: تلك حالةٌ في جهاز
# المستخدم لا يراها أحد ولا يضبطها المستودع. وقد كلّفتنا جولة: كان
# `.firebaserc` يحمل المفتاح `dafault` (خطأ إملائي)، فسجّلت الأداة
# «dafault» **اسماً لمشروع**، وبقيت مسجَّلة بعد تصحيح الملف — فصار النشر
# يطلب مشروعاً اسمه `dafault` لا وجود له، بخطأ 403 لا يذكر السبب.
#
# و`sed` لا `python3`: هذا سكربت نشر، ولا يجوز أن يتوقّف على مفسّر قد لا
# يكون مثبَّتاً على جهاز من ينشر.
PROJECT="$(sed -n 's/.*"default"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p' .firebaserc 2>/dev/null | head -1)"

say() { printf '\n\033[1m%s\033[0m\n' "$1"; }
die() {
  printf '\n══════════════════════════════════════════════════════════════\n'
  printf '⛔ توقّف: %s\n' "$1"
  shift
  for line in "$@"; do printf '   %s\n' "$line"; done
  printf '══════════════════════════════════════════════════════════════\n\n'
  exit 1
}

if [ -z "$PROJECT" ]; then
  die "تعذّر قراءة معرّف مشروع Firebase من .firebaserc" \
      "يجب أن يحوي الملف مفتاحاً اسمه default هكذا:" \
      '  { "projects": { "default": "<معرّف-المشروع>" } }'
fi

# ــــ ١) هل ما سننشره هو آخر شيفرة فعلاً؟ ــــ
say "١/٧  التحقّق من أن شيفرتك محدَّثة…"

BYPASSED=""

if ! git fetch --quiet origin "$BRANCH" 2>/dev/null; then
  echo "⚠ تعذّر الاتصال بالخادم للتحقّق — يُكمَل النشر بما لديك."
else
  BEHIND="$(git rev-list --count "HEAD..origin/$BRANCH" 2>/dev/null || echo 0)"
  if [ "${BEHIND:-0}" -gt 0 ]; then
    [ -z "$FORCE" ] && die "فرعك متأخّر عن الخادم بـ $BEHIND التزاماً." \
        "ستنشر شيفرة قديمة، وهذا ما يُضيّع الوقت في تشخيص أعطال مُصلَحة أصلاً." \
        "" \
        "نفّذ هذا ثم أعد المحاولة:" \
        "  git fetch origin && git reset --hard origin/$BRANCH"
    BYPASSED="متأخّر بـ $BEHIND التزاماً"
  fi
fi

DIRTY_FILES="$(worktree_dirty_files)"
if [ -n "$DIRTY_FILES" ]; then
  # ــــ الدرن: ثلاثة أحوالٍ لا حالٌ واحدة ــــ
  #
  # كان الحارس يقف على **أي** ملفٍّ متّسخ بحجّة أنه «يمنع git pull من
  # الدمج فتبقى شيفرتك قديمة». وأوقف نشراً مرّتين على `analysis_options.yaml`
  # — إعدادُ محلّل شيفرة لا أثر له في المنصة المنشورة إطلاقاً.
  #
  # والحجّة غير صحيحة أصلاً: `git` لا يرفض الدمج إلا على ملفٍّ **يمسّه
  # الوارد**. وأسوأ منها أن الفحص يجري مستقلاً عن `BEHIND`: فمن كان
  # محدَّثاً تماماً — ولا شيء يُسحب — كان يُوقَف ويُقال له إن شيفرته ستبقى
  # قديمة. عبارةٌ لا تصف شيئاً.
  #
  # وحارسٌ يصيح بلا ذئب يُعلّم صاحبه تجاهل الصيحة حين يجيء الذئب. فصار
  # يقف حيث الحجّة صحيحة وحدها.
  DIRTY_LINES=()
  DIRTY_ARGS=""
  while IFS= read -r _f; do
    [ -n "$_f" ] || continue
    DIRTY_LINES+=("  • $_f")
    # `:/` يثبّت المسار عند جذر المستودع: `git status` يطبع المسارات من
    # الجذر، والسكربت يُنفَّذ من داخل `gov_executive_platform/` — فأمرٌ بلا
    # تثبيت يُردّ بـ«did not match any file». وقد قِيس: نُفّذ الأمر
    # المقترَح حرفاً، فسقط قبل التثبيت ونجح بعده.
    DIRTY_ARGS="$DIRTY_ARGS \":/$_f\""
  done <<EOF
$DIRTY_FILES
EOF

  if [ "$(worktree_dirt_is_generated "$DIRTY_FILES")" = "yes" ]; then
    # ملفّا القفل وحدهما: أدواتنا كتبتهما لا أنت، فلا يُوقَف النشر عليهما.
    echo "ℹ ملفّا القفل معدَّلان — أدوات البناء تُعيد كتابتهما، ولا يمنع ذلك النشر:"
    echo "$DIRTY_FILES" | sed 's/^/    • /'
  elif [ "$(worktree_dirt_blocks_pull "$DIRTY_FILES" "$BRANCH")" = "yes" ]; then
    # هنا وحدها الحجّة صحيحة: الخادم غيّر هذه الملفات بعينها وأنت غيّرتها،
    # فالسحب سيُرفض فعلاً وتبقى شيفرتك قديمة.
    CONFLICT_LINES=()
    while IFS= read -r _f; do
      [ -n "$_f" ] && CONFLICT_LINES+=("  • $_f")
    done <<EOF
$(worktree_conflicting_files "$DIRTY_FILES" "$BRANCH")
EOF
    [ -z "$FORCE" ] && die "تعديلاتك تتعارض مع ما وصل من الخادم في:" \
        "${CONFLICT_LINES[@]}" \
        "" \
        "هذه الملفات غيّرها الخادم وغيّرتَها أنت، فـ«git pull» سيُرفض" \
        "وتبقى شيفرتك قديمة دون أن تدري." \
        "" \
        "لرؤية ما تغيّر عندك:" \
        "  git diff" \
        "" \
        "ولاسترجاعها إلى نسخة الخادم (وتفقد تعديلك عليها):" \
        "  git checkout --$DIRTY_ARGS"
    BYPASSED="${BYPASSED:+${BYPASSED}، و}تعارضٌ مع الوارد"
  else
    # فرعٌ محدَّث ودرنٌ لا يمسّه أحد: لا شيء يُسحب، ولا شيء يُعرقَل.
    # وتعديلك شيفرةٌ تخصّك — ونشرُها هو ما طلبتَه. فيُقال ويمضي.
    echo "ℹ لديك تعديلات محلية، **وستُنشر كما هي**:"
    echo "$DIRTY_FILES" | sed 's/^/    • /'
    echo "  ولا تمنع السحب: الخادم لم يغيّر هذه الملفات، فلا تعارض عليها."
    if [ "$(worktree_dirt_is_whitespace_only)" = "yes" ]; then
      # سببٌ يتكرّر بلا أن يُرى، فيُسمّى: محرّرٌ يبدّل نهايات الأسطر أو
      # يُقلّم مسافة، فيعود الملف «معدَّلاً» بعد كل استرجاع.
      echo "  ℹ الفرق في المسافات ونهايات الأسطر فحسب — على الأرجح محرّرك."
    fi
    echo "  ولاسترجاعها إلى نسخة الخادم إن لم تقصدها:"
    echo "    git checkout --$DIRTY_ARGS"
  fi
fi

COMMIT="$(git rev-parse --short HEAD)"
# الصدق هنا مهم: `--force` يتجاوز الحارس، ولا يجوز أن يطبع السكربت «محدَّثة»
# وهي ليست كذلك — فتلك هي الطمأنينة الكاذبة التي بُني الحارس ضدّها أصلاً.
if [ -n "$BYPASSED" ]; then
  echo "⚠ تجاوزتَ الحارس بـ --force ($BYPASSED)."
  echo "  ما سيُنشر ليس نسخة الخادم — الفرع: $BRANCH · الالتزام: $COMMIT"
else
  echo "✔ الشيفرة محدَّثة — الفرع: $BRANCH · الالتزام: $COMMIT"
fi

# ــــ ٢) البناء ــــ
say "٢/٧  بناء نسخة الويب…"
./tool/build_web.sh

# ــــ ٣) الدوال قبل القواعد ــــ
#
# الترتيب مقصود: القواعد الجديدة **تعتمد على** دوالّ جديدة. فقاعدة عضوية
# المشروع صارت تمنع الكتابة المباشرة وتُحيل إلى `setProjectTeam` — فلو نُشرت
# القواعد أولاً وفشل نشر الدوال (فوترة، حصّة، انقطاع) لبقي مدير الإدارة
# عاجزاً عن تعديل فريق مشروعه بلا بديل.
#
# و`set -e` يوقف السكربت هنا إن فشلت الدوال، فلا تُضيَّق قاعدةٌ بلا خلفها ما
# يخدمها.
#
# ملاحظة: من هذه الدوال واحدةٌ **مجدولة** (تقرير السابعة صباحاً). وأول نشرٍ
# لها يحتاج تفعيل Cloud Scheduler في المشروع؛ ويطلبه Firebase صراحةً في
# رسالة الخطأ مع رابط التفعيل إن لم يكن مفعَّلاً. ولا يمنع ذلك بقية الدوال:
# هي تُنشر كما هي، والتقرير وحده لا يعمل حتى يُفعَّل.
say "٣/٧  نشر الدوال (الاعتماد وختم الصلاحيات وفريق المشروع والتقرير اليومي)…"
firebase deploy --project "$PROJECT" --only functions

# ــــ ٤) القواعد ــــ
#
# قبل الموقع عمداً: القواعد هي التي تفتح البيانات. ولو نُشر الموقع أولاً
# وفشلت القواعد، لبقي المستخدمون على واجهة جديدة ببيانات محجوبة — وهو أسوأ
# ما يمكن أن يظهر لهم.
# ــ والفهارس معها، لا بعدها ولا بيد ــ
#
# `firestore.indexes.json` كان في المستودع ولا ينشره شيء: كان يُنشأ الفهرس
# يدوياً من الرابط الذي تطبعه Firestore في وجه أول مستخدمٍ يُخفق استعلامُه.
# فأيُّ استعلامٍ جديد يصل الوزارة **مكسوراً** حتى يشتكي أحد.
#
# والفهرسُ يُبنى في دقائق بعد نشره، فيبقى الاستعلامُ يُخفق في أثنائها —
# وذلك مقولٌ في الشاشة لا مخفيّ.
say "٤/٧  نشر قواعد قاعدة البيانات وفهارسها (هي التي تقرّر من يرى ماذا)…"
firebase deploy --project "$PROJECT" --only firestore:rules,firestore:indexes

# ــــ ٥) قواعد التخزين ــــ
#
# التخزين قد لا يكون مفعَّلاً في المشروع بعد، وذلك **ليس عطلاً**: المرفقات
# بالرابط تعمل بدونه تماماً. فيُتخطّى بلطف بدل إفشال النشر كله.

# هل يقول نصّ الخطأ إن التخزين غير مفعَّل؟
#
# لا يكفي أن نعرف أن الأمر فشل: كانت الرسالة تقول «على الأرجح أن Storage غير
# مفعَّل» لـ**أي** فشل — انقطاع شبكة، أو صلاحية ناقصة، أو خطأ في القواعد
# نفسها. فيُصرَف القارئ عن سببه الحقيقي إلى سببٍ مُخمَّن. وهذه الدالة تفصل
# الحالتين بتوقيع رسالة Firebase نفسها.
storage_not_enabled() {
  printf '%s' "$1" | grep -qiE "has not been set up|storage bucket|no default bucket"
}

say "٥/٧  نشر قواعد التخزين (مرفقات التحديثات اليومية)…"
STORAGE_RESULT="skipped"
STORAGE_OUT="$(firebase deploy --project "$PROJECT" --only storage 2>&1)" && STORAGE_OK=1 || STORAGE_OK=0
printf '%s\n' "$STORAGE_OUT"

if [ "$STORAGE_OK" = "1" ]; then
  echo "✔ نُشرت قواعد التخزين."
  STORAGE_RESULT="deployed"
elif storage_not_enabled "$STORAGE_OUT"; then
  # ليست حالة عطل، بل خطوة إعداد لم تُخطَ بعد — فتُقال كما هي، بلا لهجة إنذار.
  echo ""
  echo "ℹ التخزين (Storage) غير مفعَّل في المشروع، فتُخطّى قواعده."
  echo "  وهذا لا يمنع النشر ولا يعطّل المنصة: إرفاق الملفات **برابط** يعمل بلا تخزين."
  echo "  ولتفعيل رفع الملفات (PDF/وورد/إكسل/صور):"
  echo "    Firebase Console ← Build ← Storage ← Get started"
  echo "  ثم أعد تشغيل هذا الأمر فتُنشَر القواعد ويعمل الرفع."
  echo ""
  STORAGE_RESULT="not-enabled"
else
  # فشلٌ لسببٍ آخر: الخطأ مطبوع أعلاه كما ورد، ولا يُنسب إلى التخزين المعطَّل.
  echo ""
  echo "⚠ فشل نشر قواعد التخزين **لسبب غير كونه معطَّلاً** — انظر الخطأ أعلاه."
  echo "  لا تتجاهله: قد يكون خطأً في storage.rules أو صلاحية ناقصة أو انقطاع شبكة."
  echo "  والنشر يكمل، لكن قواعد التخزين تبقى على نسختها السابقة."
  echo ""
  STORAGE_RESULT="failed"
fi

# ــــ ٦) الموقع ــــ
say "٦/٧  نشر الموقع…"
firebase deploy --project "$PROJECT" --only hosting

# ــــ ٧) التحقّق: هل يخدم الموقع فعلاً ما بنيناه؟ ــــ
#
# هذه الخطوة أُضيفت بعد جولة كاملة ضاعت: كان السكربت **يطلب** من المستخدم أن
# يقارن الالتزام بنفسه بعد النشر، وهو طلبٌ يُنسى — فبقي يرى واجهةً أقدم من
# الشيفرة بعشرات الالتزامات ويصف أعطالاً مُصلَحة أصلاً، ونحن نشخّص شيفرةً لا
# أحد يراها.
#
# فالسكربت يسأل الموقع بنفسه الآن. وإخفاق الاتصال ليس إخفاق نشر — يُقال ذلك
# ولا يُفشَل النشر عليه.
LIVE_RESULT="unknown"
say "٧/٧  التحقّق من أن الموقع يخدم هذا الالتزام…"
if live_commit_matches "$COMMIT" "https://${PROJECT}.web.app/build.json"; then
  echo "✔ الموقع يخدم الالتزام $COMMIT."
  LIVE_RESULT="ok"
elif [ -z "$LIVE_COMMIT" ]; then
  # لم يُقرأ شيء بعد كل المحاولات: انقطاعٌ أو حجب. وإخفاق الاتصال ليس
  # إخفاق نشر، فلا يُفشَل النشر عليه.
  echo "⚠ تعذّر الوصول إلى الموقع للتحقّق — قد يكون حجباً في شبكتك."
  echo "  النشر تمّ، والتحقّق وحده لم يقع."
else
  LIVE_RESULT="mismatch"
fi

printf '\n══════════════════════════════════════════════════════════════\n'
if [ "$LIVE_RESULT" = "mismatch" ]; then
  printf '⛔ النشر تمّ، لكن الموقع ما زال يخدم التزاماً آخر.\n\n'
  printf '   بنينا ونشرنا: %s\n' "$COMMIT"
  printf '   والموقع يخدم: %s\n\n' "${LIVE_COMMIT:-غير معروف}"
  printf '   لا تفتح المنصة قبل معالجة هذا — ستصف أعطالاً في شيفرة قديمة.\n\n'
  # وتأخّرُ الانتشار لم يعد سبباً محتملاً: سُئل الموقع مراراً على مدى نحو
  # دقيقة. فإعادة النشر — وهي النصيحة التي كانت هنا — مُكلفة ولا تحلّ شيئاً،
  # وتُبدَّل بما بقي من أسبابٍ ومعها ما يكشف كلاً منها.
  printf '   وقد انتظرنا انتشار التحديث (%s محاولات) فلم ينزل — فالسبب ليس التأخّر.\n\n' "$LIVE_CHECK_TRIES"
  printf '   والباقي سببان، وهذان الأمران يكشفانهما:\n\n'
  printf '   ١) هل النشر يذهب إلى موقعٍ آخر في المشروع نفسه؟\n'
  printf '        firebase hosting:sites:list --project %s\n\n' "$PROJECT"
  printf '   ٢) وهل ما بُني هو ما نُشر؟\n'
  printf '        cat build/web/build.json\n'
  printf '══════════════════════════════════════════════════════════════\n\n'
  exit 1
fi
printf '✔ اكتمل النشر بالكامل.\n\n'
printf '   الالتزام المنشور: %s   (الفرع: %s)\n' "$COMMIT" "$BRANCH"
# حصيلة التخزين في الملخّص: بغيرها يظن القارئ أن كل شيء نُشر، وقد تُخطّيت
# خطوةٌ كاملة قبل عشرة أسطر.
case "$STORAGE_RESULT" in
  deployed)    printf '   قواعد التخزين: نُشرت.\n' ;;
  not-enabled) printf '   قواعد التخزين: تُخطّيت (التخزين غير مفعَّل — الإرفاق بالرابط يعمل).\n' ;;
  failed)      printf '   قواعد التخزين: ⚠ فشلت لسبب غير التعطيل — راجع الخطأ أعلاه.\n' ;;
esac
printf '\n'
printf '   افتح المنصة وحدّث الصفحة تحديثاً قوياً:\n'
printf '     ⌘ + Shift + R   على الماك\n'
printf '     Ctrl + Shift + R على ويندوز\n'
printf '\n'
