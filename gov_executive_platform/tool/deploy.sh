#!/usr/bin/env bash
#
# نشر المنصة كاملةً بأمر واحد:  ./tool/deploy.sh
#
# لماذا سكربت بدل أربعة أوامر؟
#
# لأن النشر أجزاء منفصلة على Firebase، ونسيان أيٍّ منها لا يُنتج رسالة خطأ —
# بل منصةً تبدو سليمة وتتصرّف تصرّفاً قديماً:
#
#   • قواعد قاعدة البيانات (firestore.rules) — هي التي تقرّر من يقرأ ماذا.
#     نسيانها يعني شاشات فارغة ولافتة حمراء، مهما كانت شيفرة الموقع جديدة.
#   • قواعد التخزين (storage.rules) — مرفقات التحديثات اليومية.
#   • الدوال (functions) — الاعتماد وختم الصلاحيات على بطاقات الدخول.
#   • الموقع (hosting) — الواجهة التي يراها المستخدم.
#
# وقد ضاعت ثلاث جولات تشخيص على هذا بالضبط: شيفرة مبنيّة ومرفوعة، وموقع
# منشور بنصفها، وقواعد لم تُنشر إطلاقاً.
#
# والحارس في الخطوة الأولى ليس تزيّداً: `build_web.sh` كان **يحذّر** من الفرع
# المتأخّر، والتحذير يمرّ في سيل مخرجات البناء فلا يُقرأ. هنا **يتوقّف**.
#
# للتجاوز عمداً (نشر شيفرة محلية لم تُرفع بعد):  ./tool/deploy.sh --force
set -euo pipefail

cd "$(dirname "$0")/.."

FORCE=""
[ "${1:-}" = "--force" ] && FORCE="yes"

BRANCH="$(git rev-parse --abbrev-ref HEAD 2>/dev/null || echo '?')"

say() { printf '\n\033[1m%s\033[0m\n' "$1"; }
die() {
  printf '\n══════════════════════════════════════════════════════════════\n'
  printf '⛔ توقّف: %s\n' "$1"
  shift
  for line in "$@"; do printf '   %s\n' "$line"; done
  printf '══════════════════════════════════════════════════════════════\n\n'
  exit 1
}

# ــــ ١) هل ما سننشره هو آخر شيفرة فعلاً؟ ــــ
say "١/٦  التحقّق من أن شيفرتك محدَّثة…"

BYPASSED=""

if ! git fetch --quiet origin "$BRANCH" 2>/dev/null; then
  echo "⚠ تعذّر الاتصال بالخادم للتحقّق — يُكمَل النشر بما لديك."
else
  BEHIND="$(git rev-list --count "HEAD..origin/$BRANCH" 2>/dev/null || echo 0)"
  if [ "${BEHIND:-0}" -gt 0 ]; then
    [ -z "$FORCE" ] && die "فرعك متأخّر عن الخادم بـ $BEHIND التزاماً." \
        "ستنشر شيفرة قديمة، وهذا ما يُضيّع الوقت في تشخيص أعطال مُصلَحة أصلاً." \
        "" \
        "نفّذ هذا ثم أعد المحاولة:" \
        "  git fetch origin && git reset --hard origin/$BRANCH"
    BYPASSED="متأخّر بـ $BEHIND التزاماً"
  fi
fi

if [ -n "$(git status --porcelain -- . ':(exclude)build' 2>/dev/null)" ]; then
  [ -z "$FORCE" ] && die "لديك تعديلات محلية غير محفوظة." \
      "وهي ما يمنع «git pull» من الدمج، فتبقى شيفرتك قديمة دون أن تدري." \
      "" \
      "للتخلّص منها والعودة إلى نسخة الخادم:" \
      "  git reset --hard origin/$BRANCH"
  BYPASSED="${BYPASSED:+$BYPASSED، و}تعديلات محلية غير محفوظة"
fi

COMMIT="$(git rev-parse --short HEAD)"
# الصدق هنا مهم: `--force` يتجاوز الحارس، ولا يجوز أن يطبع السكربت «محدَّثة»
# وهي ليست كذلك — فتلك هي الطمأنينة الكاذبة التي بُني الحارس ضدّها أصلاً.
if [ -n "$BYPASSED" ]; then
  echo "⚠ تجاوزتَ الحارس بـ --force ($BYPASSED)."
  echo "  ما سيُنشر ليس نسخة الخادم — الفرع: $BRANCH · الالتزام: $COMMIT"
else
  echo "✔ الشيفرة محدَّثة — الفرع: $BRANCH · الالتزام: $COMMIT"
fi

# ــــ ٢) البناء ــــ
say "٢/٦  بناء نسخة الويب…"
./tool/build_web.sh

# ــــ ٣) القواعد أولاً ــــ
#
# قبل الموقع عمداً: القواعد هي التي تفتح البيانات. ولو نُشر الموقع أولاً
# وفشلت القواعد، لبقي المستخدمون على واجهة جديدة ببيانات محجوبة — وهو أسوأ
# ما يمكن أن يظهر لهم.
say "٣/٦  نشر قواعد قاعدة البيانات (هي التي تقرّر من يرى ماذا)…"
firebase deploy --only firestore:rules

# ــــ ٤) قواعد التخزين ــــ
#
# التخزين قد لا يكون مفعَّلاً في المشروع بعد، وذلك **ليس عطلاً**: المرفقات
# بالرابط تعمل بدونه تماماً. فيُتخطّى بلطف بدل إفشال النشر كله.

# هل يقول نصّ الخطأ إن التخزين غير مفعَّل؟
#
# لا يكفي أن نعرف أن الأمر فشل: كانت الرسالة تقول «على الأرجح أن Storage غير
# مفعَّل» لـ**أي** فشل — انقطاع شبكة، أو صلاحية ناقصة، أو خطأ في القواعد
# نفسها. فيُصرَف القارئ عن سببه الحقيقي إلى سببٍ مُخمَّن. وهذه الدالة تفصل
# الحالتين بتوقيع رسالة Firebase نفسها.
storage_not_enabled() {
  printf '%s' "$1" | grep -qiE "has not been set up|storage bucket|no default bucket"
}

say "٤/٦  نشر قواعد التخزين (مرفقات التحديثات اليومية)…"
STORAGE_RESULT="skipped"
STORAGE_OUT="$(firebase deploy --only storage 2>&1)" && STORAGE_OK=1 || STORAGE_OK=0
printf '%s\n' "$STORAGE_OUT"

if [ "$STORAGE_OK" = "1" ]; then
  echo "✔ نُشرت قواعد التخزين."
  STORAGE_RESULT="deployed"
elif storage_not_enabled "$STORAGE_OUT"; then
  # ليست حالة عطل، بل خطوة إعداد لم تُخطَ بعد — فتُقال كما هي، بلا لهجة إنذار.
  echo ""
  echo "ℹ التخزين (Storage) غير مفعَّل في المشروع، فتُخطّى قواعده."
  echo "  وهذا لا يمنع النشر ولا يعطّل المنصة: إرفاق الملفات **برابط** يعمل بلا تخزين."
  echo "  ولتفعيل رفع الملفات (PDF/وورد/إكسل/صور):"
  echo "    Firebase Console ← Build ← Storage ← Get started"
  echo "  ثم أعد تشغيل هذا الأمر فتُنشَر القواعد ويعمل الرفع."
  echo ""
  STORAGE_RESULT="not-enabled"
else
  # فشلٌ لسببٍ آخر: الخطأ مطبوع أعلاه كما ورد، ولا يُنسب إلى التخزين المعطَّل.
  echo ""
  echo "⚠ فشل نشر قواعد التخزين **لسبب غير كونه معطَّلاً** — انظر الخطأ أعلاه."
  echo "  لا تتجاهله: قد يكون خطأً في storage.rules أو صلاحية ناقصة أو انقطاع شبكة."
  echo "  والنشر يكمل، لكن قواعد التخزين تبقى على نسختها السابقة."
  echo ""
  STORAGE_RESULT="failed"
fi

# ــــ ٥) الدوال ــــ
say "٥/٦  نشر الدوال (الاعتماد وختم الصلاحيات)…"
firebase deploy --only functions

# ــــ ٦) الموقع ــــ
say "٦/٦  نشر الموقع…"
firebase deploy --only hosting

printf '\n══════════════════════════════════════════════════════════════\n'
printf '✔ اكتمل النشر بالكامل.\n\n'
printf '   الالتزام المنشور: %s   (الفرع: %s)\n' "$COMMIT" "$BRANCH"
# حصيلة التخزين في الملخّص: بغيرها يظن القارئ أن كل شيء نُشر، وقد تُخطّيت
# خطوةٌ كاملة قبل عشرة أسطر.
case "$STORAGE_RESULT" in
  deployed)    printf '   قواعد التخزين: نُشرت.\n' ;;
  not-enabled) printf '   قواعد التخزين: تُخطّيت (التخزين غير مفعَّل — الإرفاق بالرابط يعمل).\n' ;;
  failed)      printf '   قواعد التخزين: ⚠ فشلت لسبب غير التعطيل — راجع الخطأ أعلاه.\n' ;;
esac
printf '\n'
printf '   افتح المنصة وحدّث الصفحة تحديثاً قوياً:\n'
printf '     ⌘ + Shift + R   على الماك\n'
printf '     Ctrl + Shift + R على ويندوز\n'
printf '\n'
printf '   ثم انظر سطر «الإصدار» أسفل اسمك في الشريط الجانبي:\n'
printf '   يجب أن ينتهي بـ «· %s». فإن لم ينتهِ بها فالنشر لم يصل متصفحك بعد.\n' "$COMMIT"
printf '══════════════════════════════════════════════════════════════\n\n'
