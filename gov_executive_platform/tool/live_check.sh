#!/usr/bin/env bash
#
# هل يخدم الموقع المنشور الالتزامَ الذي بنيناه؟
# يُستعمل بـ `source ./tool/live_check.sh` من deploy.sh.
#
# ــــ لماذا إعادة المحاولة، ولماذا هي أهمّ ممّا تبدو؟ ــــ
#
# كان الفحص ينادي `curl` **مرّة واحدة** فور رجوع `firebase deploy`، وشبكة
# توزيع Firebase تحتاج ثوانيَ حتى تُقدّم الملف الجديد على حوافّها. فأطلق
# الحارس إنذاراً كاذباً على نشرٍ سليم: «لا تفتح المنصة — ستصف أعطالاً في
# شيفرة قديمة»، والشيفرة لم تكن قديمة.
#
# وهذا الحارس بالذات أُضيف بعد جولة تشخيصٍ كاملة ضاعت: كان المستخدم يرى
# واجهةً أقدم من الشيفرة بعشرات الالتزامات ويصف أعطالاً مُصلَحة أصلاً.
#
# **وحارسٌ يُنذر كذباً يُدرَّب صاحبه على تجاهله.** فأول صياحٍ حقيقي بعده
# يمرّ بلا انتباه، وقد تعوّد القارئ أن «هذه رسالته المعتادة». فالإنذار
# الكاذب لا يُضعف الحارس بل يُبطله — ولذلك يُصلَح ولا يُتجاهَل.
#
# والقراءة مفصولة عن الحكم (`live_commit_reader`) لتُختبر بلا شبكة: تأخّر
# الانتشار عارضٌ زمني لا يُعاد بالطلب، فلو لم يُفصل لبقيت الإعادة نفسها
# خارج مدى أي اختبار — وهي بالضبط ما أُضيف.
#
# ملاحظة: يعمل على macOS بـbash 3.2، فلا ميزات bash 4 هنا.

# كم مرّة يُسأل الموقع، وكم ينتظر بينها.
LIVE_CHECK_TRIES="${LIVE_CHECK_TRIES:-6}"
LIVE_CHECK_WAIT="${LIVE_CHECK_WAIT:-10}"

# يقرأ الالتزام الحيّ من build.json. تُستبدَل في الاختبار بقارئٍ مزيّف.
live_commit_reader() {
  local url="$1"
  curl -fsS --max-time 25 -H 'Cache-Control: no-cache' "$url" 2>/dev/null \
    | sed -n 's/.*"commit"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p' | head -1
}

# آخر التزامٍ قرأناه — يُقرأ بعد الإخفاق لتُطبع قيمته في رسالة الإنذار.
LIVE_COMMIT=""

# يُرجع 0 عند التطابق، و1 بعد نفاد المحاولات.
#
#   live_commit_matches <الالتزام المتوقَّع> <العنوان>
live_commit_matches() {
  local want="$1" url="$2" i=1
  while :; do
    LIVE_COMMIT="$(live_commit_reader "$url")"
    [ "$LIVE_COMMIT" = "$want" ] && return 0
    [ "$i" -ge "$LIVE_CHECK_TRIES" ] && return 1
    # لا صمت أثناء الانتظار: سكربتٌ يقف دقيقةً بلا كلمة يبدو معلَّقاً،
    # فيُوقفه من ينشر بـCtrl+C في منتصف تحقّقٍ كان سينجح.
    if [ -z "$LIVE_COMMIT" ]; then
      echo "  … لم يُقرأ شيء من الموقع (محاولة $i من $LIVE_CHECK_TRIES) — إعادة بعد ${LIVE_CHECK_WAIT}ث"
    else
      echo "  … الموقع ما زال على $LIVE_COMMIT (محاولة $i من $LIVE_CHECK_TRIES) — إعادة بعد ${LIVE_CHECK_WAIT}ث"
    fi
    sleep "$LIVE_CHECK_WAIT"
    i=$((i + 1))
  done
}
