#!/usr/bin/env bash
# حارس: حدُّ ختم البطاقة لا يُرفع، والعلامةُ لا تُكتب لختمٍ لم يُغيّر شيئاً.
#
# ــــ الحلقةُ التي أوقفت منصّة الوزارة ــــ
#
# `syncMyClaims` تُعيد ختمَ بطاقة الدخول، والخادمُ يكتب `claimsUpdatedAt`
# على مستند المستخدم ليوقظ متصفّحه فيُجدّد رمزه. فإن كُتبت العلامةُ في كل
# ختم — أو رُفع حدُّ «محاولةٌ واحدة لكل جلسة» عند رؤيتها — انعقدت الحلقة:
#
#   علامة ⇒ يقظة ⇒ فحصُ بطاقة ⇒ اختلاف ⇒ syncMyClaims ⇒ ختم ⇒ علامة ⇒ …
#
# وكلُّ لفّةٍ تُلغي كلَّ اشتراكات المستخدم وتُعيدها، فتبدو المنصّةُ تُعيد
# التحميل بلا توقّف ولا تستقرّ. وهذا حارسُ الطرفين معاً.
set -eu
cd "$(dirname "$0")/../.."

fail() { printf '⛔ %s\n' "$1" >&2; exit 1; }

STORE="lib/data/app_store.dart"
CORE="functions/src/claims_stamp.ts"

[ -f "$STORE" ] || fail "لم يُعثر على $STORE"
[ -f "$CORE" ]  || fail "لم يُعثر على $CORE"

# ــ الطرفُ الأوّل: الحدُّ لا يُرفع ــ
#
# `_claimsSyncTried` تُرفع مرّةً ولا تُخفض. وخفضُها في مستمع مستند
# المستخدم هو ما عقد الحلقة.
if grep -n '_claimsSyncTried[[:space:]]*=[[:space:]]*false' "$STORE" \
     | grep -v '^[0-9]*:[[:space:]]*//' \
     | grep -v 'bool _claimsSyncTried' >/dev/null 2>&1; then
  fail "حدُّ ختم البطاقة يُرفع في $STORE — وهذا يعقد حلقةً لا تنتهي.
   راجع tool/test/claims_loop_test.sh، والتعليق فوق claimsRestamped."
fi

# ــ الطرفُ الثاني: العلامةُ خبرُ تغيُّر ــ
#
# وكان الفحصُ نصّاً حرفيّاً: `sameClaims(before, claims)`. فلمّا صار الخاتمُ
# يحمل المفاتيحَ الغائبة (`withCarriedClaims`) تغيّر اسمُ ما يُكتب، فصاح
# الحارسُ على تغييرٍ لم يكسر شيئاً — **وهذا أهونُ عطلَي الحارس**، فنظيرُه
# أن يُعاد ترتيبُ السطر فيمرّ وقد سقط الفحص.
#
# فصار يُسأل عن **المعنى**: أن يكون ما يُقارَن هو **ما يُكتب فعلاً**. فيُقرأ
# اسمُ ما يُمرَّر إلى `setClaims`، ويُشترط أن تقارن `sameClaims` ذلك الاسمَ
# بعينه. ومن كتب `setClaims(uid, full)` وقارن `claims` تُكتب علامتُه لكلّ
# ختمٍ ولو لم يُغيّر شيئاً — وهو عقدُ الحلقة بعينه.
WRITTEN="$(sed -n 's/.*deps\.setClaims(uid, \([A-Za-z_][A-Za-z0-9_]*\)).*/\1/p' "$CORE" | head -1)"
if [ -z "$WRITTEN" ]; then
  fail "لم يُعرف ما تكتبه stampClaims في $CORE — تغيّر شكلُ نداء setClaims،
   فالحارسُ لم يعد يفحص شيئاً. راجع tool/test/claims_loop_test.sh."
fi
grep -q "sameClaims(before, ${WRITTEN})" "$CORE" \
  || fail "stampClaims تكتب «${WRITTEN}» وتقارن شيئاً آخر في $CORE —
   فستُكتب العلامةُ لكلّ ختمٍ ولو لم يُغيّر شيئاً، وتنعقد الحلقة."

printf '✔ حارسُ حلقة بطاقة الدخول: الحدُّ لا يُرفع، والعلامةُ خبرُ تغيُّر.\n'
