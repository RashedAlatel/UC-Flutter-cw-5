#!/usr/bin/env bash
#
# حارس أوامر Firebase: كلُّ أمرٍ يُملى على القارئ يحمل `--project`.
#
# ــــ العطل الذي أوجده ــــ
#
# أداةُ Firebase تحفظ «المشروع النشط» في إعداداتها **خارج المستودع**،
# مفهرسةً بمسار المجلّد. فالأمرُ المجرّد:
#
#     firebase deploy --only firestore:indexes
#
# لا يقرأ `.firebaserc` ابتداءً — بل يلتقط تلك الحالةَ المحفوظة. ومرّةً
# حُفظ فيها «dafault» (خطأ إملائي كان في `.firebaserc` ثمّ صُحّح)، فبقي
# محفوظاً بعد تصحيح الملفّ. فصار النشرُ يطلب مشروعاً لا وجود له، ويسقط بـ:
#
#     HTTP Error: 403, Caller does not have required permission
#     to use project dafault
#
# وهي رسالةٌ لا تذكر أين المشكلة ولا أنّ الملفّ سليم.
#
# ووقع هذا **مرّتين**. في الأولى كُتب `tool/deploy.sh` ليقرأ المعرّف من
# `.firebaserc` ويمرّره صراحةً في كلّ أمر — فحُصّن مسارُ النشر. وفي الثانية
# وقع العطلُ من **نصٍّ مكتوب**: لافتةٌ في المنصّة أملت الأمرَ مجرّداً،
# فقرأه صاحبُ الجهاز ونفّذه. أي أنّ تحصينَ السكربت لا يكفي ما دامت
# الشاشاتُ والوثائق تعلّم الشكلَ المعطوب.
#
# فهذا الحارس يمنع **النوع** لا الحالة: لا أمرَ يُملى إلا ومعه `--project`.
#
# ــــ ولماذا التعليقاتُ تُستثنى ــــ
#
# التعليقُ **رواية** لا تعليم: هذا الملفّ نفسُه يعرض الشكلَ المعطوب في
# شرحه أعلاه، و`tool/deploy.sh` يروي القصّة، و`README.md` ينهى عن الأمر
# المجرّد فيضطرّ إلى ذكره. ولولا الاستثناءُ لاتّهم الحارسُ نفسَه ومَن يحذّر
# مثلَه.
#
# والفرقُ مقيس: ما كان في تعليقٍ (`#` أو `//` أو `///`) أو في اقتباس
# Markdown (`>`) فهو روايةٌ تُقرأ. وما كان في نصٍّ يُعرض للمستخدم أو في بندِ
# إرشادٍ فهو أمرٌ يُنفَّذ — وهذا وحدَه ما يُحاسَب.
#
# ــــ وثغرةُ هذا الفرز، مقيسةً لا مظنونة ــــ
#
# طفرةٌ وُضع فيها أمرٌ مجرّدٌ **داخل تعليق** (`// شغّل firebase deploy ...`)
# فمرّ الحارسُ صامتاً. وهي ثغرةٌ حقيقيّة: من يكتب تعليماً في تعليقٍ يُقرأ
# وينُفَّذ كما يُقرأ النصّ.
#
# وتُركت مفتوحةً عن قصد، لأنّ سدَّها يعني محاسبةَ كلّ روايةٍ — فيُتَّهم هذا
# الملفُّ نفسُه و`README.md` في موضع النهي، فيصير الحارسُ يشكو ممّا لا عيبَ
# فيه. **وحارسٌ يشكو بالباطل لا يُقرأ يومَ يشكو بالحقّ.**
#
# والعطلُ الذي أوجد هذا الحارس لم يكن في تعليق: كان في نصٍّ يُعرض على شاشة
# المستخدم. فالفرزُ يمسك الطريقَ الذي سلكه العطلُ فعلاً.
#
# الاستخدام:  ./tool/test/firebase_command_test.sh
set -uo pipefail

cd "$(dirname "$0")/../.."

PASS=0
FAIL=0

echo "▶ حارس أوامر Firebase"
echo ""

# ــ الملفّاتُ التي تُملي أوامرَ على قارئها ــ
#
# `lib` لأنّ نصوصَ اللافتات فيها، و`README.md` لأنّه دليلُ التنصيب، و`tool`
# لأنّ سكربتاتِه تُنفَّذ وتُقرأ معاً.
SCANNED="README.md lib tool functions/src"

# ــ ما يُعدّ أمراً: `firebase` يتلوه أمرٌ فرعيّ ــ
#
# و`firebase` وحدَها لا تكفي: الكلمةُ تقع في أسماء الحزم وفي المسارات وفي
# النثر العربيّ عشراتِ المرّات، ولا شأن لها بسطر أوامر.
INVOKE='firebase[[:space:]]\+\(deploy\|use\|hosting:\|firestore:\|functions:\|target:\)'

# ــ إسقاطُ الرواية ــ
#
# الصيغةُ من `grep -rn` هي `ملفّ:رقم:نصّ`. فيُسقَط ما كان نصُّه — بعد
# المسافات البادئة — تعليقاً أو اقتباساً.
NARRATION='^[^:]*:[0-9]*:[[:space:]]*\(#\|//\|>\)'

ALL="$(grep -rn "${INVOKE}" ${SCANNED} 2>/dev/null \
  --include='*.dart' --include='*.md' --include='*.sh' --include='*.ts' \
  | grep -v '/build/' | grep -v '/node_modules/')"

ORDERS="$(printf '%s\n' "${ALL}" | grep -v "${NARRATION}")"

# ــ الحكم ــ
echo "كلُّ أمرٍ مُملىً يحمل \`--project\`:"
NAKED="$(printf '%s\n' "${ORDERS}" | grep -v -- '--project' | grep -v '^$')"
if [ -z "${NAKED}" ]; then
  echo "  ✔ لا أمرَ مجرّداً"
  PASS=$((PASS + 1))
else
  echo "  ✗ أوامرُ تلتقط مشروعاً محفوظاً خارج المستودع وتسقط بـ403:"
  printf '%s\n' "${NAKED}" | sed 's/^/      /'
  echo ""
  echo "      الإصلاح — أحدُ اثنين:"
  echo "        • \`./tool/deploy.sh\` — يقرأ المعرّف من .firebaserc ويمرّره"
  echo "        • أو \`firebase <أمر> --project <معرّف> ...\` صراحةً"
  FAIL=$((FAIL + 1))
fi

# ــ والكاشفُ يرى ــ
#
# حارسٌ لا يُخرج شيئاً قد يكون سليمَ الشجرة، وقد يكون أعمى: تعبيرٌ لا يطابق
# شيئاً يمرّ صامتاً كما يمرّ الصحيح. فيُقاس ما رآه.
echo ""
echo "والكاشفُ يرى:"
N_ALL="$(printf '%s\n' "${ALL}" | grep -c . )"
N_ORD="$(printf '%s\n' "${ORDERS}" | grep -c . )"
N_NAR=$((N_ALL - N_ORD))
if [ "${N_ALL}" -ge 5 ] && [ "${N_ORD}" -ge 1 ]; then
  echo "  ✔ قُرئ ${N_ALL} استدعاءً: ${N_ORD} أمراً و${N_NAR} روايةً في تعليق"
  PASS=$((PASS + 1))
else
  echo "  ✗ قُرئ ${N_ALL} استدعاءً فقط (${N_ORD} أمراً) — التعبيرُ لا يطابق"
  echo "      حارسٌ لا يرى شيئاً يمرّ صامتاً، وصمتُه يُقرأ نجاحاً"
  FAIL=$((FAIL + 1))
fi

# ــ وإسقاطُ الرواية يُقاس هو الآخر ــ
#
# لو انكسر تعبيرُ الرواية فأسقط كلَّ شيء، لصار الحارسُ يمرّ دائماً — وهو
# أخطرُ من سقوطه.
echo ""
echo "وإسقاطُ الرواية يفرّق ولا يبتلع:"
if [ "${N_NAR}" -ge 1 ] && [ "${N_ORD}" -ge 1 ]; then
  echo "  ✔ التعليقاتُ تُستثنى والأوامرُ تبقى"
  PASS=$((PASS + 1))
else
  echo "  ✗ الفرزُ ابتلع جانباً كاملاً: ${N_ORD} أمراً و${N_NAR} روايةً"
  FAIL=$((FAIL + 1))
fi

echo ""
echo "══════════════════════════════"
echo "نجح: ${PASS} · فشل: ${FAIL}"
[ "${FAIL}" -eq 0 ]
