#!/usr/bin/env bash
#
# حارس التحقّق من النشر: هل يعيد المحاولة قبل أن يحكم؟
#
# ــــ لماذا هذا الاختبار موجود ــــ
#
# أطلق الحارس إنذاراً كاذباً على نشرٍ سليم: سأل الموقع مرّة واحدة فور رجوع
# `firebase deploy`، وشبكة التوزيع لم تكن قدّمت الملف الجديد بعد. فقيل
# للناشر «لا تفتح المنصة — ستصف أعطالاً في شيفرة قديمة»، والشيفرة جديدة.
#
# والإنذار الكاذب لا يُضعف الحارس بل **يُبطله**: يتعلّم صاحبه تجاهله، فيمرّ
# الصياح الحقيقي بلا انتباه.
#
# وتأخّرُ الانتشار عارضٌ زمني لا يُعاد بالطلب، فلا تُختبر الإعادة بنشرٍ
# حقيقي. ولهذا فُصلت القراءة عن الحكم: يُحقن هنا قارئٌ مزيّف يحاكي التأخّر.
#
# الاستخدام:  ./tool/test/live_check_test.sh
set -uo pipefail

cd "$(dirname "$0")/../.."

# لا انتظار حقيقي في الاختبار: المقصود منطق الإعادة لا مرور الوقت.
LIVE_CHECK_WAIT=0
LIVE_CHECK_TRIES=6

# shellcheck source=tool/live_check.sh
. ./tool/live_check.sh
LIVE_CHECK_WAIT=0

PASS=0
FAIL=0

ok() { echo "  ✔ $1"; PASS=$((PASS + 1)); }
no() { echo "  ✗ $1"; echo "      $2"; FAIL=$((FAIL + 1)); }

# ــ قارئٌ مزيّف، وعدّادُه في **ملف** لا في متغيّر ــ
#
# لأن `live_commit_matches` تقرأ عبر `$(...)`، وهي صَدَفة فرعية: أي متغيّر
# يُزاد فيها يعود إلى قيمته عند خروجها. فعدّادٌ في متغيّر يبقى صفراً مهما
# نودي القارئ — والاختبار حينها يقيس نفسه لا الشيفرة.
COUNTER="$(mktemp)"
trap 'rm -f "$COUNTER"' EXIT
reset_calls() { echo 0 > "$COUNTER"; }
calls() { cat "$COUNTER"; }
bump() {
  local n
  n=$(( $(cat "$COUNTER") + 1 ))
  echo "$n" > "$COUNTER"
  echo "$n"
}

fake_late() {
  local n
  n="$(bump)"
  if [ "$n" -lt 3 ]; then echo "968b298"; else echo "a96bfc8"; fi
}
fake_stuck() { bump >/dev/null; echo "968b298"; }
fake_silent() { bump >/dev/null; echo ""; }

echo "▶ حارس التحقّق من النشر"
echo ""

echo "التأخّر في الانتشار لا يُعدّ إخفاقاً:"
reset_calls
live_commit_reader() { fake_late; }
if live_commit_matches "a96bfc8" "http://x" >/dev/null 2>&1; then
  ok "الالتزام الذي يصل في المحاولة الثالثة يُقبل"
else
  no "الالتزام الذي يصل في المحاولة الثالثة يُقبل" \
     "أُخفق رغم وصوله — وهذا هو الإنذار الكاذب نفسه"
fi
# ولولا هذا لَمرّ الاختبار الأول بقارئٍ يُرجع الصحيح من أول مرّة، فلا يُثبت
# شيئاً عن الإعادة.
if [ "$(calls)" -ge 3 ]; then
  ok "وقد أُعيد السؤال فعلاً لا مرّة واحدة"
else
  no "وقد أُعيد السؤال فعلاً لا مرّة واحدة" "عدد المحاولات: $(calls)"
fi
echo ""

echo "والحكم لم يلِن — عدم التطابق يبقى إخفاقاً:"
reset_calls
live_commit_reader() { fake_stuck; }
if live_commit_matches "a96bfc8" "http://x" >/dev/null 2>&1; then
  no "موقعٌ عالقٌ على التزامٍ قديم يُخفق" "قُبل وهو لم يتطابق قط"
else
  ok "موقعٌ عالقٌ على التزامٍ قديم يُخفق"
fi
if [ "$(calls)" = "$LIVE_CHECK_TRIES" ]; then
  ok "وبعد استنفاد المحاولات كلها لا قبلها"
else
  no "وبعد استنفاد المحاولات كلها لا قبلها" \
     "المتوقَّع $LIVE_CHECK_TRIES محاولات، والواقع $(calls)"
fi
# آخر ما قُرئ يبقى محفوظاً لتُطبع قيمته في رسالة الإنذار — وبدونه تقول
# الرسالة «غير معروف» فتضيع أهمّ معلومة فيها.
if [ "$LIVE_COMMIT" = "968b298" ]; then
  ok "ويُحفظ ما قرأه ليُذكر في الرسالة"
else
  no "ويُحفظ ما قرأه ليُذكر في الرسالة" "القيمة: ${LIVE_COMMIT:-فارغة}"
fi
echo ""

# انقطاع الشبكة ليس إخفاق نشر، ويفترق عنه بأن المقروء **فارغ** لا قديم.
# وdeploy.sh يفرّق بينهما بهذا بالضبط.
echo "وانقطاع الاتصال يفترق عن عدم التطابق:"
reset_calls
live_commit_reader() { fake_silent; }
live_commit_matches "a96bfc8" "http://x" >/dev/null 2>&1
if [ -z "$LIVE_COMMIT" ]; then
  ok "لا شيء يُقرأ ⇒ القيمة فارغة لا قديمة"
else
  no "لا شيء يُقرأ ⇒ القيمة فارغة لا قديمة" "القيمة: $LIVE_COMMIT"
fi
echo ""

echo "══════════════════════════════"
echo "نجح: $PASS · فشل: $FAIL"
[ "$FAIL" -eq 0 ] || exit 1
