#!/usr/bin/env bash
# حارس: قراءةُ مستند المشروع لا تُسند نوعاً مباشرةً.
#
# ــــ الحادثةُ التي أوجبت هذا الحارس ــــ
#
# اختفت مشاريعُ وزارة العدل كلُّها — مئةٌ وأربعةٌ وثمانون — يوماً كاملاً،
# والسببُ **مستندٌ واحد** حمل `contractEndDate` نصّاً بدل ختمٍ زمني:
#
#     '2026-05-17T00:00:00.000'
#
# فرمى `as Timestamp?` عند قراءته، والقراءةُ يومَها ذرّية، فأسقط المستندُ
# الواحدُ الباقين معه. ولم يظهر على الشاشة حرفٌ واحد يقول لماذا.
#
# ــــ ولماذا حارسٌ لا اختبار ــــ
#
# لأن العطلَ لا يظهر إلا بمستندٍ من نوعٍ لم يخطر لكاتب السطر. فالاختبارُ
# يقيس ما تصوّرناه، وهذا يمنع **صنفَ** السطر كلَّه: كلُّ تاريخٍ ورقمٍ في
# `project.dart` يمرّ بـ`_date` أو `_num`، فلا يرمي أحدُهما أبداً ومهما
# كُتب في قاعدة البيانات.
#
# وقاعدةُ بياناتٍ بلا مخطَّطٍ مُلزِم لا يُؤمَن فيها نوعُ حقل. والثمنُ الذي
# دُفع مرّةً لا يُدفع ثانية.
set -eu
cd "$(dirname "$0")/../.."

MODEL="lib/models/project.dart"

[ -f "$MODEL" ] || { printf '⛔ لم يُعثر على %s\n' "$MODEL" >&2; exit 1; }

# الأسطرُ التعليقية تُستثنى: هذا الملفّ يشرح العطل بنصّه، ويذكر الإسنادَ
# الذي أوقعه. وحارسٌ يسقط على شرحِ نفسه حارسٌ لا يُبقي شرحاً.
offenders=$(
  grep -n 'as Timestamp?\|as num?' "$MODEL" \
    | grep -v '^[0-9][0-9]*:[[:space:]]*//' \
    || true
)

if [ -n "${offenders}" ]; then
  printf '⛔ إسنادُ نوعٍ مباشر في %s:\n' "$MODEL" >&2
  printf '%s\n' "${offenders}" >&2
  printf '%s\n' \
    "" \
    "   التواريخُ تُقرأ بـ_date والأرقامُ بـ_num — فنوعٌ مفاجئ في مستندٍ" \
    "   واحد لا يُسقط المشاريع كلَّها. راجع التعليق فوق _date في النموذج." >&2
  exit 1
fi

# ــ والقارئان موجودان فعلاً ــ
#
# ولولا هذا لَمرّ الحارسُ على ملفٍّ حُذف منه القارئان وأُعيدت فيه الأسنادُ
# بصيغةٍ أخرى.
for reader in '_date(Object? raw)' '_num(Object? raw)'; do
  grep -q "${reader}" "$MODEL" || {
    printf '⛔ القارئ %s غير موجود في %s\n' "${reader}" "$MODEL" >&2
    exit 1
  }
done

printf '✔ حارسُ قراءة النموذج: كلُّ تاريخٍ ورقمٍ في المشروع يمرّ بقارئٍ لا يرمي.\n'
