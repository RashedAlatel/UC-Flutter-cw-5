#!/usr/bin/env bash
# حارس: ما صار مشتركاً لا يُكتب في شاشةٍ من جديد.
#
# ــــ المرضُ الانحراف، لا التكرارُ وحدَه ــــ
#
# قِيس قبل التوحيد فوُجد:
#
#   * `_Bit` مكتوبةٌ **مرّتين متطابقتين حرفاً**.
#   * و`_ChartCard` مرّتين **منحرفتين**: عنوانٌ ١٥ في لوحة القيادة و١٤٫٥ في
#     صفحة المشروع، وواحدةٌ تقبل وصفاً ثانويّاً والأخرى لا.
#   * و`_SectionTitle` ثلاثاً، اثنتان بشريطٍ ذهبيّ **والثالثةُ شيءٌ آخر**:
#     نصٌّ بلا شريطٍ ولا فاصل.
#   * و`_Empty` **ثلاثَ صياغاتٍ مختلفة**: إطارٌ وأيقونةٌ وعنوان هنا، وسطرٌ
#     بحشوة ٢٤ هناك، ونصٌّ بحشوة ٢٨ ثالثاً.
#
# فثلاثُ شاشاتٍ تقول «لا بيانات» بثلاثة أشكال، وبطاقتا رسمٍ بعنوانين
# مختلفَي الحجم. **وهذا بعينه ما يجعل المنصةَ تبدو صفحاتٍ صُمّمت في أوقاتٍ
# مختلفة** — لا تكراراً يُكلّف سطوراً.
#
# ــــ وما يُقاس هنا ــــ
#
# لا يُعاد كتابةُ ودجةٍ صارت مشتركةً داخل شاشة. فالنسخةُ الجديدة تبدأ
# مطابقةً ثم تنحرف بتعديلٍ لا يبلغ أختَها — وهو ما وقع أربعَ مرّات.
set -eu
cd "$(dirname "$0")/../.."

PASS=0
FAIL=0
ok()  { echo "  ✔ $1"; PASS=$((PASS + 1)); }
bad() { echo "  ✗ $1"; echo "      $2"; FAIL=$((FAIL + 1)); }

# الاسمُ الخاصّ ← الودجةُ المشتركة التي تُغني عنه.
SHARED="
_Empty:AppEmptyState
_EmptyBoardNotice:AppEmptyState
_SectionTitle:SectionTitle
_ChartCard:AppCard
_Bit:MetaBit
_StatusPill:StatusPill
"

echo "▶ حارس الودجات المشتركة"
echo ""
echo "لا يُعاد كتابةُ ما صار مشتركاً:"

for row in $SHARED; do
  name="${row%%:*}"
  shared="${row##*:}"
  hits="$(grep -rn "^class ${name} extends" lib/screens lib/widgets --include=*.dart || true)"
  if [ -z "$hits" ]; then
    ok "«${name}» لا يُكتب خاصّاً — و${shared} تُغني عنه"
  else
    n="$(printf '%s\n' "$hits" | grep -c .)"
    where="$(printf '%s\n' "$hits" | cut -d: -f1 | tr '\n' ' ')"
    bad "«${name}» لا يُكتب خاصّاً" \
"وُجد ${n} نسخةً في: ${where}
      تُستبدل بـ${shared} المشتركة. ونسخةٌ جديدةٌ تبدأ مطابقةً ثم تنحرف
      بتعديلٍ لا يبلغ أختَها — وهو ما وقع أربعَ مرّات."
  fi
done
echo ""

# ــ ويحرس نفسَه ــ
#
# كاشفٌ لا يجد شيئاً لأنّ صياغةَ الإعلان تغيّرت يمرّ صامتاً. فيُقاس أنّه
# **يرى الأصنافَ الخاصّة أصلاً** في المجلّدين اللذين يفحصهما.
echo "والكاشفُ يرى:"
PRIVATE="$(grep -rc "^class _[A-Za-z]* extends" lib/screens lib/widgets --include=*.dart \
  | awk -F: '{s+=$2} END {print s+0}')"
if [ "$PRIVATE" -ge 30 ]; then
  ok "قُرئ ${PRIVATE} صنفاً خاصّاً في الشاشات والودجات"
else
  bad "قُرئت الأصنافُ الخاصّة" \
"عُدَّ ${PRIVATE} فقط — تغيّرت صياغةُ الإعلان والكاشفُ أعمى، لا أنّ الشاشات خلت منها."
fi
echo ""

echo "══════════════════════════════"
echo "نجح: $PASS · فشل: $FAIL"
[ "$FAIL" -eq 0 ] || exit 1
