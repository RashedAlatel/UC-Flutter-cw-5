#!/usr/bin/env bash
#
# حارس محمولية السكربتات: `$متغيّر` لا يلاصق حرفاً عربياً.
#
# ــــ العطل الذي أوجده ــــ
#
# سطرٌ كهذا يعمل عندي ويقتل السكربت على جهاز المستخدم:
#
#     echo "و«$gate» لا تمرّ"
#
# لأن `»` حرفٌ من بايتين (C2 BB) يلاصق اسم المتغيّر. فـ bash 5 يقف بالاسم
# عند آخر حرفٍ لاتيني، أمّا **bash 3.2 على macOS** فيبتلع البايت الأول في
# الاسم — فيصير `gate<بايت>` وهو غير معرَّف. ومع `set -u` يموت السكربت في
# مكانه قبل أن يطبع فحصاً واحداً، فلا تُرى أسطر `✗` أصلاً.
#
# ووقع هذا مرّتين، وأوقف نشر الوزارة مرّتين. وفي الأولى أُصلحت **حالةٌ
# مظنونة** (أُعيدت كتابة الأدوات) وبقي السطرُ المعطوب كما هو، فعاد العطل.
# فهذا الحارس يمنع **النوع** لا الحالة.
#
# ــــ ولماذا `LC_ALL=C` ــــ
#
# بها تعني `[^ -~]` «بايتٌ ليس حرفاً لاتينياً مطبوعاً» — وهو المعنى المقصود
# بالضبط، وهو واحدٌ في BSD وGNU. وبغيرها تختلف قراءة الصنف بين الأداتين،
# فيصير حارسُ المحمولية نفسُه غيرَ محمول.
#
# الاستخدام:  ./tool/test/shell_portability_test.sh
set -uo pipefail

cd "$(dirname "$0")/../.."

PASS=0
FAIL=0

echo "▶ حارس محمولية السكربتات"
echo ""

# ــ لا متغيّرَ عارٍ يلاصق حرفاً عربياً ــ
echo "كل \$متغيّر ملاصقٍ لحرفٍ غير لاتيني مُقوَّس:"
# والتعليقاتُ تُستثنى: لا تُنفَّذ فلا تقتل شيئاً — وهذا الملفّ نفسُه يعرض
# الشكلَ المعطوب في شرحه أعلاه، فلولا الاستثناء لَاتّهم نفسَه.
# والتصفيةُ بعد `grep -n` لتبقى أرقامُ الأسطر: الصيغة `ملف:رقم:نصّ`،
# فيُسقَط ما كان نصُّه تعليقاً.
HITS="$(LC_ALL=C grep -n '\$[A-Za-z_][A-Za-z0-9_]*[^ -~]' tool/*.sh tool/test/*.sh 2>/dev/null \
  | grep -v '^[^:]*:[0-9]*:[[:space:]]*#')"
if [ -z "${HITS}" ]; then
  echo "  ✔ لا موضعَ عارياً"
  PASS=$((PASS + 1))
else
  echo "  ✗ مواضعُ تقتل السكربت على bash 3.2:"
  printf '%s\n' "${HITS}" | sed 's/^/      /'
  echo "      الإصلاح: قوسان حول الاسم — \${name} بدل \$name"
  FAIL=$((FAIL + 1))
fi

# ــ والسكربتاتُ سليمةُ النحو، كلُّ واحدٍ منها ــ
#
# `bash -n` يقرأ ولا ينفّذ. ولا يكشف متغيّراً غيرَ معرَّف (ذلك وقتُ تشغيل)،
# لكنه يكشف قوساً ناقصاً أو `fi` منسيّاً — وهو ما يقتل سكربتاً كاملاً بلا
# أن يظهر في أي اختبار.
echo ""
echo "ولا خطأ نحوياً في سكربت:"
for f in tool/*.sh tool/test/*.sh; do
  if bash -n "${f}" 2>/dev/null; then
    PASS=$((PASS + 1))
  else
    echo "  ✗ ${f}"
    bash -n "${f}" 2>&1 | sed 's/^/      /'
    FAIL=$((FAIL + 1))
  fi
done
[ "${FAIL}" -eq 0 ] && echo "  ✔ جميعها ($(ls tool/*.sh tool/test/*.sh | wc -l | tr -d ' ') سكربتاً)"

echo ""
echo "══════════════════════════════"
echo "نجح: ${PASS} · فشل: ${FAIL}"
[ "${FAIL}" -eq 0 ] || exit 1
