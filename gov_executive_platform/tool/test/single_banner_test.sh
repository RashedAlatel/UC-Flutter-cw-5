#!/usr/bin/env bash
# حارس: لافتةُ تعذّر القراءة تُركَّب في موضعٍ واحد.
#
# ــــ ما كشفه ــــ
#
# `AppShell` يعرض `DataAccessBanner` فوق **كل** شاشة. ثم ركّبتها شاشتان
# ثانيةً في متنهما، فظهرت اللافتةُ مرّتين متطابقتين في الشاشة الواحدة —
# ولم يُلحَظ ذلك شهوراً لأنها لا تظهر إلا عند عطل. فلمّا وقع عطلٌ حقيقيّ في
# منصّة الوزارة رآها مسؤولُ النظام مكرّرة وهو يقرأ خبرَ عطلٍ مقلق.
#
# والقاعدةُ التي يحرسها: **ما يعرضه الإطارُ لا يُعاد عرضُه في متنه.**
set -eu
cd "$(dirname "$0")/../.."

SHELL_FILE="lib/widgets/app_shell.dart"

[ -f "${SHELL_FILE}" ] || { printf '⛔ لم يُعثر على %s\n' "${SHELL_FILE}" >&2; exit 1; }

# مواضعُ التركيب خارج ملفّ اللافتة نفسِه (وفيه تعريفُها) وخارج الاختبارات.
mounts=$(
  grep -rn 'DataAccessBanner()' lib \
    | grep -v '^lib/widgets/data_access_banner\.dart:' \
    || true
)

count=$(printf '%s' "${mounts}" | grep -c . || true)

if [ "${count}" != "1" ]; then
  printf '⛔ لافتةُ تعذّر القراءة مركَّبةٌ في %s موضعاً لا موضعٍ واحد:\n' "${count}" >&2
  printf '%s\n' "${mounts}" >&2
  printf '%s\n' \
    "" \
    "   موضعُها الوحيد ${SHELL_FILE} — وهو إطارُ كلّ شاشة." \
    "   وتركيبُها في شاشةٍ بعينها يُظهرها مرّتين لقارئها." >&2
  exit 1
fi

printf '%s\n' "${mounts}" | grep -q "^${SHELL_FILE}:" || {
  printf '⛔ اللافتةُ مركَّبةٌ في موضعٍ واحد لكنه ليس %s:\n' "${SHELL_FILE}" >&2
  printf '%s\n' "${mounts}" >&2
  exit 1
}

printf '✔ حارسُ اللافتة: موضعٌ واحد، وهو إطارُ كلّ شاشة.\n'
